CREATE TABLE public."PostTranslation" (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id BIGINT NOT NULL,
    locale VARCHAR(8) NOT NULL,
    status VARCHAR(16) NOT NULL,
    title TEXT NOT NULL,
    description TEXT NOT NULL,
    content TEXT NOT NULL,
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    source_hash VARCHAR(64) NOT NULL,
    reviewed_at TIMESTAMPTZ(6),
    created_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT "PostTranslation_post_id_fkey"
        FOREIGN KEY (post_id) REFERENCES public."Post"(id)
        ON DELETE CASCADE ON UPDATE NO ACTION,
    CONSTRAINT "PostTranslation_locale_check"
        CHECK (locale IN ('en', 'ja', 'zh')),
    CONSTRAINT "PostTranslation_status_check"
        CHECK (status IN ('draft', 'published')),
    CONSTRAINT "PostTranslation_source_hash_check"
        CHECK (source_hash ~ '^[a-f0-9]{64}$'),
    CONSTRAINT "PostTranslation_review_state_check"
        CHECK (
            (status = 'draft' AND reviewed_at IS NULL)
            OR (status = 'published' AND reviewed_at IS NOT NULL)
        ),
    CONSTRAINT "PostTranslation_post_locale_status_key"
        UNIQUE (post_id, locale, status)
);

CREATE INDEX "PostTranslation_locale_status_idx"
    ON public."PostTranslation" (locale, status);

ALTER TABLE public."PostTranslation" ENABLE ROW LEVEL SECURITY;

-- Translations are read and written through the trusted Next.js server only.
REVOKE ALL ON TABLE public."PostTranslation" FROM anon, authenticated, service_role;
REVOKE ALL ON SEQUENCE public."PostTranslation_id_seq" FROM anon, authenticated, service_role;

COMMENT ON TABLE public."PostTranslation" IS
    'Draft and published multilingual versions of Post content';
